def owner_module(name):
    try:
        owner = PUBLIC_SYMBOLS[name]
    except KeyError:
        raise AttributeError(name) from None
    return import_module("dkss_app." + owner)


def resolve(name, app):
    if name == "app":
        return app
    if name in app.extensions["dkss"]:
        return app.extensions["dkss"][name]
    if name in app.config:
        return app.config[name]
    return getattr(owner_module(name), name)
